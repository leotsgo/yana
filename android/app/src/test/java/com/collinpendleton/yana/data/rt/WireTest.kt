/**
 * The wire codec against bytes the server's own encoder produced: the
 * golden arrays below were emitted by Go's vmihailenco/msgpack from
 * internal/rt's ClientMessage and ServerMessage structs, so an exact
 * match here is what keeps the Android client speaking the same frames
 * as the server and the web.
 */
class WireTest {
    private val note = "01ARZ3NDEKTSV4RRFFQ69G5FAV"

    private fun golden(name: String): ByteArray =
        GOLDEN.first { it.first == name }.second

    @Test
    fun encodesExactlyWhatTheServerEncoderProduces() {
        assertArrayEquals(
            golden("SUB_FULL"),
            encodeClientFrame(ClientFrame(t = Rt.SUB, n = note, sv = byteArrayOf(1, 2, 3, 4), a = "user:ada")),
        )
        assertArrayEquals(
            golden("SUB_EMPTY_SV"),
            encodeClientFrame(ClientFrame(t = Rt.SUB, n = note, a = "user:ada")),
        )
        assertArrayEquals(
            golden("UPD"),
            encodeClientFrame(ClientFrame(t = Rt.UPD, n = note, u = byteArrayOf(0, 1, 0xff.toByte()), a = "user:ada")),
        )
        assertArrayEquals(golden("PING"), encodeClientFrame(ClientFrame(t = Rt.PING)))
        assertArrayEquals(golden("UNSUB"), encodeClientFrame(ClientFrame(t = Rt.UNSUB, n = note)))
        assertArrayEquals(
            golden("AW"),
            encodeClientFrame(ClientFrame(t = Rt.AW, n = note, p = byteArrayOf(9, 9))),
        )
        val long = ByteArray(400) { it.toByte() }
        assertArrayEquals(
            golden("UPD_LONG"),
            encodeClientFrame(ClientFrame(t = Rt.UPD, n = note, u = long, a = "user:ada")),
        )
        assertArrayEquals(
            golden("WATCH"),
            encodeClientFrame(ClientFrame(t = Rt.WATCH, s = "work")),
        )
    }

    @Test
    fun decodesWhatTheServerEncoderProduced() {
        fun dec(name: String) = decodeServerFrame(golden(name))

        dec("SUBD_DELTA").let {
            assertEquals(Rt.SUBD, it?.t)
            assertEquals(note, it?.n)
            assertArrayEquals(byteArrayOf(1, 2), it?.u!!)
        }
        dec("SUBD_EMPTY").let {
            assertEquals(Rt.SUBD, it?.t)
            assertNull(it?.u)
        }
        dec("UPD_SVR").let {
            assertEquals(Rt.UPD, it?.t)
            assertEquals("filesystem", it?.a)
        }
        dec("AW_SVR").let {
            assertEquals(Rt.AW, it?.t)
            assertEquals("user:bob", it?.a)
            assertArrayEquals(byteArrayOf(7), it?.p!!)
        }
        dec("MOVED").let {
            assertEquals(Rt.MOVED, it?.t)
            assertEquals("notes/deep/renamed.md", it?.path)
        }
        dec("DELETED").let {
            assertEquals(Rt.DELETED, it?.t)
            assertEquals(note, it?.n)
        }
        dec("ERR").let {
            assertEquals(Rt.ERR, it?.t)
            assertEquals("rate_limited", it?.c)
            assertEquals("update rate exceeded; batch more per message", it?.r)
        }
        dec("ERR_LONG_REASON").let {
            assertEquals("invalid", it?.c)
            assertEquals("x".repeat(40), it?.r)
        }
        dec("WATCHD").let {
            assertEquals(Rt.WATCHED, it?.t)
            assertEquals("main", it?.s)
        }
        dec("CHG").let {
            assertEquals(Rt.CHANGED, it?.t)
            assertEquals(note, it?.n)
            assertEquals("work/todo.md", it?.path)
        }
        dec("PONG").let {
            assertEquals(Rt.PONG, it?.t)
        }
    }

    @Test
    fun roundTripsBothDirections() {
        val client = ClientFrame(t = Rt.UPD, n = note, u = byteArrayOf(1, 2, 3), a = "user:ada")
        val back = decodeClientFrame(encodeClientFrame(client))
        assertEquals(client.t, back?.t)
        assertEquals(client.n, back?.n)
        assertArrayEquals(client.u!!, back?.u!!)
        assertEquals(client.a, back?.a)
        val watch = ClientFrame(t = Rt.WATCH, s = "work")
        val watchBack = decodeClientFrame(encodeClientFrame(watch))
        assertEquals(watch.s, watchBack?.s)
        assertEquals(watch.t, watchBack?.t)
        val server = ServerFrame(t = Rt.ERR, n = note, c = "invalid", r = "a reason")
        assertEquals(server, decodeServerFrame(encodeServerFrame(server)))
    }

    @Test
    fun skipsUnknownFieldsAndTypes() {
        // A newer server adds a field carrying an int and an array; the
        // frame must still decode.
        val out = Msgpack.Writer()
        out.mapHeader(4)
        out.str("t"); out.str("upd")
        out.str("n"); out.str(note)
        out.str("u"); out.bin(byteArrayOf(9))
        out.str("future"); out.bin(byteArrayOf(1))
        val decoded = decodeServerFrame(out.bytes())
        assertEquals(Rt.UPD, decoded?.t)
        assertArrayEquals(byteArrayOf(9), decoded?.u!!)

        val second = Msgpack.Writer()
        second.mapHeader(3)
        second.str("t"); second.str("upd")
        second.str("n"); second.str(note)
        second.str("count"); second.bin(byteArrayOf(5)) // bin, not int: writer's shapes
        assertEquals(Rt.UPD, decodeServerFrame(second.bytes())?.t)
    }

    @Test
    fun rejectsGarbage() {
        assertNull(decodeServerFrame(ByteArray(0)))
        assertNull(decodeServerFrame(byteArrayOf(0xc0.toByte()))) // nil, not a map
        assertNull(decodeServerFrame(byteArrayOf(0x81.toByte(), 0xa1.toByte(), 0x6e))) // truncated
        assertNull(decodeServerFrame(byteArrayOf(0x90.toByte()))) // array, not a map
        // A map without a t field is not a frame.
        val out = Msgpack.Writer()
        out.mapHeader(1)
        out.str("n"); out.str(note)
        assertNull(decodeServerFrame(out.bytes()))
        // Trailing bytes are refused.
        val ping = encodeClientFrame(ClientFrame(t = Rt.PING))
        assertNull(decodeClientFrame(ping + byteArrayOf(0)))
    }

    @Test
    fun writerPicksMinimalFormats() {
        // str8 boundary and bin16 boundary both encode and decode back.
        val s = "x".repeat(255)
        val frame = encodeServerFrame(ServerFrame(t = Rt.ERR, r = s))
        assertTrue(frame[0] == 0x82.toByte()) // two fields
        val decoded = decodeServerFrame(frame)
        assertEquals(s, decoded?.r)

        val big = ByteArray(300) { 7 }
        val f2 = encodeClientFrame(ClientFrame(t = Rt.UPD, n = note, u = big))
        assertTrue(f2.contains(0xc5.toByte())) // bin16
        assertArrayEquals(big, decodeClientFrame(f2)?.u!!)
    }

